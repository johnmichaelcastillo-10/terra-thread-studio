<?php
/**
 * Headless installer: generates salts, installs WordPress into the SQLite
 * database, activates the theme + plugins and seeds the studio catalogue.
 * Idempotent — re-running only fills in what is missing.
 *
 * Env: TT_URL (default http://localhost:8090), TT_ADMIN_USER, TT_ADMIN_PASS, TT_ADMIN_EMAIL
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

$root = dirname( __DIR__ );

/* 1. Per-checkout keys and salts (wp-config.php loads this file). */
$salts_file = $root . '/config/salts.php';
if ( ! is_file( $salts_file ) ) {
	$keys  = array( 'AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT' );
	$lines = array( '<?php', '// Generated by bin/install.php — do not commit.' );
	foreach ( $keys as $key ) {
		$lines[] = sprintf( "define( '%s', '%s' );", $key, bin2hex( random_bytes( 32 ) ) );
	}
	file_put_contents( $salts_file, implode( "\n", $lines ) . "\n" );
	echo "    generated config/salts.php\n";
}

/* 2. Bootstrap WordPress in install mode. */
$url                    = getenv( 'TT_URL' ) ?: 'http://localhost:8090';
$_SERVER['HTTP_HOST']   = parse_url( $url, PHP_URL_HOST ) . ( parse_url( $url, PHP_URL_PORT ) ? ':' . parse_url( $url, PHP_URL_PORT ) : '' );
$_SERVER['REQUEST_URI'] = '/';
define( 'WP_INSTALLING', true );

require $root . '/public/wordpress/wp-load.php';
require_once ABSPATH . 'wp-admin/includes/upgrade.php';
require_once ABSPATH . 'wp-admin/includes/plugin.php';

if ( ! is_blog_installed() ) {
	$user  = getenv( 'TT_ADMIN_USER' ) ?: 'admin';
	$pass  = getenv( 'TT_ADMIN_PASS' ) ?: wp_generate_password( 16, false );
	$email = getenv( 'TT_ADMIN_EMAIL' ) ?: 'studio@terrathread.test';

	wp_install( 'Terra & Thread Studio', $user, $email, true, '', $pass );
	echo "    WordPress installed\n";
	echo "    ┌──────────────────────────────────────────\n";
	echo "    │ Admin user:     $user\n";
	echo "    │ Admin password: $pass\n";
	echo "    └──────────────────────────────────────────\n";

	// Remove the default "Hello world!" post and "Sample Page".
	foreach ( array( 1, 2 ) as $default_id ) {
		wp_delete_post( $default_id, true );
	}
	wp_delete_comment( 1, true );
} else {
	echo "    WordPress already installed\n";
}

/* 3. Site options. */
update_option( 'blogdescription', 'Handmade goods & masterclasses from a small clay-and-cloth studio' );
update_option( 'permalink_structure', '/%postname%/' );
update_option( 'default_comment_status', 'closed' );
update_option( 'date_format', 'F j, Y' );
update_option( 'time_format', 'g:i a' );

/* 4. Plugins + theme. */
foreach ( array( 'sqlite-database-integration/load.php', 'terra-thread-core/terra-thread-core.php' ) as $plugin ) {
	if ( ! is_plugin_active( $plugin ) ) {
		$result = activate_plugin( $plugin );
		if ( is_wp_error( $result ) ) {
			fwrite( STDERR, "Could not activate $plugin: " . $result->get_error_message() . "\n" );
			exit( 1 );
		}
		echo "    activated $plugin\n";
	}
}

if ( 'terra-thread' !== get_stylesheet() ) {
	switch_theme( 'terra-thread' );
	echo "    activated theme terra-thread\n";
}

/* 5. Schema + seed data. init already fired before the plugin was active, so
      register the content model by hand before seeding and flushing rewrites. */
\TerraThread\Core\register_content_model();
\TerraThread\Core\Schema\install();
\TerraThread\Core\Seeder\run();

flush_rewrite_rules( false );

echo "    ready at $url\n";
